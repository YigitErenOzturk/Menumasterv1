-- Clean policies so this script can be re-run.
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies where schemaname = 'public'
    and tablename in ('profiles','restaurants','menu_items','reservations','reviews') loop
    execute format('drop policy if exists %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

-- Profiles
create policy "profiles_select_public" on public.profiles for select using (true);
create policy "profiles_update_own" on public.profiles for update
using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());

-- Restaurants
create policy "restaurants_select_public" on public.restaurants for select using (true);
create policy "restaurants_insert_own" on public.restaurants for insert
with check (auth_user_id = auth.uid());
create policy "restaurants_update_own" on public.restaurants for update
using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());

-- Menu
create policy "menu_select_public" on public.menu_items for select using (true);
create policy "menu_insert_owner" on public.menu_items for insert
with check (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid()));
create policy "menu_update_owner" on public.menu_items for update
using (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid()))
with check (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid()));
create policy "menu_delete_owner" on public.menu_items for delete
using (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid()));

-- Reservations
create policy "reservations_select_user_or_restaurant" on public.reservations for select
using (
  exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid())
  or
  exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid())
);
create policy "reservations_insert_user" on public.reservations for insert
with check (exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid()));
create policy "reservations_update_user_or_restaurant" on public.reservations for update
using (
  exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid())
  or
  exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid())
)
with check (
  exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid())
  or
  exists (select 1 from public.restaurants r where r.id = restaurant_id and r.auth_user_id = auth.uid())
);

-- Reviews
create policy "reviews_select_public" on public.reviews for select using (true);
create policy "reviews_insert_own" on public.reviews for insert
with check (exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid()));
create policy "reviews_update_own" on public.reviews for update
using (exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid()))
with check (exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid()));
create policy "reviews_delete_own" on public.reviews for delete
using (exists (select 1 from public.profiles p where p.id = user_id and p.auth_user_id = auth.uid()));

-- Helpful view
create or replace view public.restaurant_summary with (security_invoker = true) as
select r.id, r.name, r.email, r.phone_number, r.description, r.address, r.city, r.image_url,
       r.rating, r.created_at,
       count(distinct m.id) as menu_item_count,
       count(distinct rev.id) as review_count
from public.restaurants r
left join public.menu_items m on m.restaurant_id = r.id
left join public.reviews rev on rev.restaurant_id = r.id
group by r.id;

